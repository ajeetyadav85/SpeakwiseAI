/**
 * Creates a custom prompt item when the user types their own topic or word
 */
export const createCustomPrompt = (input: string): GoalTopicItem => {
  const trimmed = input.trim();
  const isSingleWord = !trimmed.includes(' ') && trimmed.length <= 25;

  if (isSingleWord) {
    return {
      id: 'custom_' + Date.now(),
      category: 'Custom Word',
      categoryEmoji: '✨',
      type: 'WORD',
      word: trimmed,
      prompt: `Speak about: "${trimmed}". Incorporate this word naturally and explain its meaning and significance.`,
      hint: `Define "${trimmed}", share personal context or an example, and summarize its relevance.`,
      suggestedDurationSeconds: 60,
    };
  }

  return {
    id: 'custom_' + Date.now(),
    category: 'Custom Topic',
    categoryEmoji: '✍️',
    type: 'CUSTOM',
    prompt: trimmed,
    hint: 'Structure your speech with an opening thesis, 2 supporting arguments, and a clear takeaway.',
    suggestedDurationSeconds: 60,
  };
};
